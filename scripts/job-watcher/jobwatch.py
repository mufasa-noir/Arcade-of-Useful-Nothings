#!/usr/bin/env python3
"""jobwatch - poll job boards, forums and channels, write fresh matches to a Markdown file.

Usage:
    python jobwatch.py --check              # test every source, print what it returns (no files written)
    python jobwatch.py                      # one run: fetch, filter, append NEW matches to jobs.md
    python jobwatch.py --watch 15           # keep running, one pass every 15 minutes
    python jobwatch.py --dry-run            # show what would be added, write nothing
    python jobwatch.py --only RemoteOK      # restrict to named source(s)
"""

from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
from pathlib import Path
from urllib import robotparser
from urllib.parse import parse_qsl, urlencode, urljoin, urlparse, urlunparse

import feedparser
import requests
import yaml
from bs4 import BeautifulSoup
from dateutil import parser as dateparser
from requests.adapters import HTTPAdapter
from urllib3.util.retry import Retry

warnings.filterwarnings("ignore", module="bs4")
log = logging.getLogger("jobwatch")

UA = "Mozilla/5.0 (compatible; jobwatch/1.0; personal job-alert tool)"
ROBOT_TOKEN = "jobwatch"
MARKER = "<!-- NEW-RUNS-BELOW -->"
MD_HEADER = (
    "# Job leads\n\n"
    "Generated by jobwatch. Newest runs first. Tick the boxes as you follow up; "
    "your edits are preserved.\n\n" + MARKER + "\n"
)


# --------------------------------------------------------------------------- model
@dataclass
class Job:
    title: str
    link: str
    source: str
    company: str = ""
    location: str = ""
    body: str = ""
    posted: datetime | None = None
    extra: str = ""  # e.g. external apply link found in a Telegram post
    matched: list[str] = field(default_factory=list)
    score: int = 0


@dataclass
class Search:
    keywords: list
    exclude: list
    locations: list
    title_only: bool


# --------------------------------------------------------------------------- helpers
def clean(text) -> str:
    if not text:
        return ""
    return re.sub(r"\s+", " ", BeautifulSoup(str(text), "html.parser").get_text(" ")).strip()


def to_dt(value) -> datetime | None:
    if value in (None, "", 0):
        return None
    try:
        if isinstance(value, datetime):
            d = value
        elif isinstance(value, time.struct_time):
            d = datetime(*value[:6])
        elif isinstance(value, (int, float)) or str(value).isdigit():
            n = float(value)
            d = datetime.fromtimestamp(n / 1000 if n > 1e11 else n, tz=timezone.utc)
        else:
            d = dateparser.parse(str(value))
        return d if d.tzinfo else d.replace(tzinfo=timezone.utc)
    except (ValueError, OverflowError, TypeError):
        return None


def make_session() -> requests.Session:
    s = requests.Session()
    s.headers.update({"User-Agent": UA, "Accept-Language": "en"})
    retry = Retry(total=3, backoff_factor=1.5, status_forcelist=(429, 500, 502, 503, 504),
                  allowed_methods=("GET",), respect_retry_after_header=True)
    s.mount("https://", HTTPAdapter(max_retries=retry))
    s.mount("http://", HTTPAdapter(max_retries=retry))
    return s


def get_json(http, url, timeout=30):
    r = http.get(url, timeout=timeout)
    r.raise_for_status()
    return r.json()


_robots: dict[str, robotparser.RobotFileParser] = {}


def check_robots(http, url: str) -> None:
    """Refuse to scrape HTML pages that robots.txt disallows."""
    p = urlparse(url)
    base = f"{p.scheme}://{p.netloc}"
    rp = _robots.get(base)
    if rp is None:
        rp = robotparser.RobotFileParser()
        try:
            r = http.get(base + "/robots.txt", timeout=10)
            rp.parse(r.text.splitlines() if r.status_code == 200 else [])
        except requests.RequestException:
            rp.parse([])
        _robots[base] = rp
    if not rp.can_fetch(ROBOT_TOKEN, url):
        raise PermissionError(f"robots.txt disallows {url}")


# --------------------------------------------------------------------------- fetchers
FETCHERS = {}


def fetcher(name):
    def deco(fn):
        FETCHERS[name] = fn
        return fn
    return deco


@fetcher("rss")
def f_rss(src, http):
    r = http.get(src["url"], timeout=30)
    r.raise_for_status()
    feed = feedparser.parse(r.content)
    out = []
    for e in feed.entries:
        title, company = clean(e.get("title", "")), ""
        if src.get("title_format") == "company: title" and ": " in title:
            company, title = title.split(": ", 1)
        body = e.get("summary") or ((e.get("content") or [{}])[0].get("value", ""))
        out.append(Job(title, e.get("link", ""), src["name"], company, body=clean(body),
                       posted=to_dt(e.get("published_parsed") or e.get("updated_parsed"))))
    return out


@fetcher("reddit")
def f_reddit(src, http):
    s = dict(src, url=f"https://www.reddit.com/r/{src['subreddit']}/new/.rss?limit=50")
    return f_rss(s, http)


@fetcher("remoteok")
def f_remoteok(src, http):
    out = []
    for d in get_json(http, "https://remoteok.com/api"):
        if not isinstance(d, dict) or "position" not in d:
            continue
        body = clean(d.get("description", "")) + " " + " ".join(d.get("tags") or [])
        out.append(Job(clean(d["position"]), d.get("url", ""), src["name"], d.get("company", ""),
                       d.get("location", ""), body, to_dt(d.get("epoch") or d.get("date"))))
    return out


@fetcher("remotive")
def f_remotive(src, http):
    data = get_json(http, "https://remotive.com/api/remote-jobs")
    return [Job(clean(d["title"]), d["url"], src["name"], d.get("company_name", ""),
                d.get("candidate_required_location", ""), clean(d.get("description", "")),
                to_dt(d.get("publication_date"))) for d in data.get("jobs", [])]


@fetcher("arbeitnow")
def f_arbeitnow(src, http):
    data = get_json(http, "https://www.arbeitnow.com/api/job-board-api")
    return [Job(clean(d["title"]), d["url"], src["name"], d.get("company_name", ""),
                d.get("location", ""), clean(d.get("description", "")) + " " + " ".join(d.get("tags") or []),
                to_dt(d.get("created_at"))) for d in data.get("data", [])]


@fetcher("hn_hiring")
def f_hn_hiring(src, http):
    """Latest monthly 'Ask HN: Who is hiring?' thread; each top-level comment is a posting."""
    hits = get_json(http, "https://hn.algolia.com/api/v1/search_by_date?tags=story,author_whoishiring&hitsPerPage=6")["hits"]
    thread = next((h for h in hits if "who is hiring" in (h.get("title") or "").lower()), None)
    if not thread:
        return []
    item = get_json(http, f"https://hn.algolia.com/api/v1/items/{thread['objectID']}", timeout=60)
    out = []
    for c in item.get("children", []):
        text = c.get("text") or ""
        if not text:
            continue
        first = clean(re.split(r"<p>", text, maxsplit=1)[0])[:160]
        out.append(Job(first, f"https://news.ycombinator.com/item?id={c['id']}", src["name"],
                       body=clean(text), posted=to_dt(c.get("created_at"))))
    return out


@fetcher("hn_jobs")
def f_hn_jobs(src, http):
    ids = get_json(http, "https://hacker-news.firebaseio.com/v0/jobstories.json")[: src.get("limit", 30)]
    out = []
    for i in ids:
        d = get_json(http, f"https://hacker-news.firebaseio.com/v0/item/{i}.json") or {}
        if d.get("title"):
            out.append(Job(clean(d["title"]), d.get("url") or f"https://news.ycombinator.com/item?id={i}",
                           src["name"], body=clean(d.get("text", "")), posted=to_dt(d.get("time"))))
    return out


@fetcher("greenhouse")
def f_greenhouse(src, http):
    out = []
    for co in src["companies"]:
        data = get_json(http, f"https://boards-api.greenhouse.io/v1/boards/{co}/jobs")
        for d in data.get("jobs", []):
            out.append(Job(clean(d["title"]), d["absolute_url"], src["name"], co,
                           (d.get("location") or {}).get("name", ""), posted=to_dt(d.get("updated_at"))))
        time.sleep(0.5)
    return out


@fetcher("lever")
def f_lever(src, http):
    out = []
    for co in src["companies"]:
        for d in get_json(http, f"https://api.lever.co/v0/postings/{co}?mode=json"):
            cat = d.get("categories") or {}
            out.append(Job(clean(d["text"]), d["hostedUrl"], src["name"], co, cat.get("location", ""),
                           clean(d.get("descriptionPlain", "")), to_dt(d.get("createdAt"))))
        time.sleep(0.5)
    return out


@fetcher("ashby")
def f_ashby(src, http):
    out = []
    for co in src["companies"]:
        data = get_json(http, f"https://api.ashbyhq.com/posting-api/job-board/{co}")
        for d in data.get("jobs", []):
            if d.get("isListed", True):
                out.append(Job(clean(d["title"]), d["jobUrl"], src["name"], co, d.get("location", ""),
                               clean(d.get("descriptionPlain", "")), to_dt(d.get("publishedAt"))))
        time.sleep(0.5)
    return out


@fetcher("telegram")
def f_telegram(src, http):
    """Public Telegram channels that have the web preview enabled (t.me/s/<channel>)."""
    ch = src["channel"].lstrip("@")
    r = http.get(f"https://t.me/s/{ch}", timeout=30)
    r.raise_for_status()
    soup = BeautifulSoup(r.text, "html.parser")
    out = []
    for m in soup.select("div.tgme_widget_message"):
        txt = m.select_one(".tgme_widget_message_text")
        date_a = m.select_one("a.tgme_widget_message_date")
        if not txt or not date_a or not date_a.get("href"):
            continue
        ext = next((a["href"] for a in txt.select("a[href]")
                    if not re.search(r"(^|//)(t|telegram)\.me", a["href"])), "")
        for br in txt.find_all("br"):
            br.replace_with("\n")
        lines = [ln.strip() for ln in txt.get_text().splitlines() if ln.strip()]
        if not lines:
            continue
        t = m.select_one("time")
        out.append(Job(lines[0][:160], date_a["href"], src["name"], body=" ".join(lines),
                       posted=to_dt(t.get("datetime") if t else None), extra=ext))
    return out


@fetcher("html_links")
def f_html_links(src, http):
    """Generic scraper: every <a> whose absolute URL matches link_pattern is treated as a posting."""
    pat, out, seen = re.compile(src["link_pattern"]), [], set()
    for page in range(1, src.get("pages", 1) + 1):
        url = src["url"].replace("{page}", str(page))
        check_robots(http, url)
        r = http.get(url, timeout=30)
        r.raise_for_status()
        for a in BeautifulSoup(r.text, "html.parser").select("a[href]"):
            link = urljoin(url, a["href"])
            title = clean(a.get_text(" "))
            if link in seen or not pat.search(link) or len(title) < 4:
                continue
            seen.add(link)
            out.append(Job(title[:200], link, src["name"]))
        time.sleep(1)
    return out


@fetcher("html")
def f_html(src, http):
    """CSS-selector scraper for boards where html_links is too blunt.
    Needs: url, item, title, link. Optional: company, location (selectors relative to item)."""
    check_robots(http, src["url"])
    r = http.get(src["url"], timeout=30)
    r.raise_for_status()
    out = []
    for it in BeautifulSoup(r.text, "html.parser").select(src["item"]):
        t, a = it.select_one(src["title"]), it.select_one(src["link"]) if src["link"] != "self" else it
        if not t or not a or not a.get("href"):
            continue
        pick = lambda sel: clean(it.select_one(sel).get_text(" ")) if sel and it.select_one(sel) else ""
        out.append(Job(clean(t.get_text(" ")), urljoin(src["url"], a["href"]), src["name"],
                       pick(src.get("company")), pick(src.get("location")), clean(it.get_text(" "))))
    return out


# --------------------------------------------------------------------------- matching
def compile_terms(words):
    out = []
    for w in words or []:
        w = str(w).strip()
        if w:
            left = r"\b" if w[0].isalnum() else ""
            right = r"\b" if w[-1].isalnum() else ""
            out.append((w, re.compile(left + re.escape(w) + right, re.I)))
    return out


def evaluate(job: Job, s: Search, max_age_days: int, now: datetime) -> bool:
    if job.posted and max_age_days and now - job.posted > timedelta(days=max_age_days):
        return False
    if any(p.search(job.title) for _, p in s.exclude):
        return False
    body = f"{job.location} {job.body[:6000]}"
    if s.locations and not any(p.search(f"{job.title} {body}") for _, p in s.locations):
        return False
    head = f"{job.title} {job.company}"
    job.matched, job.score = [], 0
    for kw, p in s.keywords:
        if p.search(head):
            job.matched.append(kw)
            job.score += 3
        elif not s.title_only and p.search(body):
            job.matched.append(kw)
            job.score += 1
    return bool(job.matched)


def norm_link(u: str) -> str:
    p = urlparse(u)
    q = [(k, v) for k, v in parse_qsl(p.query)
         if not k.lower().startswith("utm_") and k.lower() not in {"ref", "source", "fbclid", "gclid"}]
    return urlunparse((p.scheme.lower(), p.netloc.lower(), p.path.rstrip("/"), "", urlencode(q), ""))


def job_keys(j: Job) -> list[str]:
    h = lambda s: hashlib.sha1(s.encode("utf-8")).hexdigest()[:16]
    keys = [h(norm_link(j.link))] if j.link else []
    if j.company:  # same role cross-posted on several boards
        keys.append(h("tc:" + re.sub(r"\W+", "", (j.title + j.company).lower())))
    return keys


# --------------------------------------------------------------------------- output
def md_esc(s: str) -> str:
    return re.sub(r"([\\`*_\[\]<>])", r"\\\1", s)


def render_section(jobs: list[Job], when: datetime) -> str:
    stamp = when.astimezone().strftime("%Y-%m-%d %H:%M %Z")
    lines = [f"## {stamp} - {len(jobs)} new", ""]
    for j in sorted(jobs, key=lambda x: (-x.score, -(x.posted.timestamp() if x.posted else 0))):
        who = " - " + md_esc(j.company) if j.company else ""
        loc = f" ({md_esc(j.location)})" if j.location else ""
        posted = j.posted.astimezone().strftime("%Y-%m-%d") if j.posted else "unknown"
        lines += [f"- [ ] **{md_esc(j.title[:160])}**{who}{loc}",
                  f"  - Link: <{j.link}>"]
        if j.extra:
            lines.append(f"  - Apply link in post: <{j.extra}>")
        lines.append(f"  - Source: {md_esc(j.source)} | Posted: {posted} | Matched: "
                     + ", ".join(f"`{m}`" for m in j.matched))
    return "\n".join(lines) + "\n"


def write_md(path: Path, jobs: list[Job], when: datetime) -> None:
    text = path.read_text(encoding="utf-8") if path.exists() else MD_HEADER
    if MARKER not in text:
        text = MD_HEADER + "\n" + text
    head, tail = text.split(MARKER, 1)
    new = head + MARKER + "\n\n" + render_section(jobs, when) + "\n" + tail.lstrip("\n")
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(new, encoding="utf-8")
    tmp.replace(path)


def notify(cfg: dict, fresh: list[Job]) -> None:
    n = cfg.get("notify") or {}
    if not n.get("ntfy_topic") or not fresh:
        return
    body = "\n".join(f"{j.title[:90]} - {j.company or j.source}" for j in fresh[:8])
    try:
        requests.post(f"{n.get('ntfy_server', 'https://ntfy.sh')}/{n['ntfy_topic']}",
                      data=body.encode("utf-8"), timeout=10,
                      headers={"Title": f"{len(fresh)} new job lead(s)", "Click": fresh[0].link})
    except (requests.RequestException, UnicodeEncodeError) as e:
        log.warning("notification failed: %s", e)


# --------------------------------------------------------------------------- state
def load_state(p: Path) -> dict:
    try:
        s = json.loads(p.read_text(encoding="utf-8"))
    except (FileNotFoundError, json.JSONDecodeError):
        s = {}
    s.setdefault("seen", {})
    s.setdefault("last_fetch", {})
    return s


def save_state(p: Path, s: dict, now: datetime) -> None:
    cutoff = (now - timedelta(days=120)).isoformat(timespec="seconds")
    s["seen"] = {k: v for k, v in s["seen"].items() if v >= cutoff}
    tmp = p.with_suffix(".tmp")
    tmp.write_text(json.dumps(s), encoding="utf-8")
    tmp.replace(p)


# --------------------------------------------------------------------------- run
def load_config(path: Path) -> dict:
    cfg = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    if not cfg.get("sources"):
        sys.exit("config has no sources")
    if not (cfg.get("search") or {}).get("keywords"):
        sys.exit("config.search.keywords is empty - add at least one keyword")
    return cfg


def fetch_source(src: dict) -> list[Job]:
    fn = FETCHERS.get(src.get("type"))
    if not fn:
        raise ValueError(f"unknown source type {src.get('type')!r}")
    return fn(src, make_session())


def active_sources(cfg, only):
    return [s for s in cfg["sources"]
            if s.get("enabled", True) and (not only or s["name"] in only)]


def run_once(cfg: dict, base: Path, args) -> int:
    now = datetime.now(timezone.utc)
    state_path = base / cfg.get("state_file", ".jobwatch_state.json")
    out_path = base / cfg.get("output", "jobs.md")
    state = load_state(state_path)
    s = cfg["search"]
    search = Search(compile_terms(s["keywords"]), compile_terms(s.get("exclude")),
                    compile_terms(s.get("locations")), bool(s.get("title_only", False)))

    due = []
    for src in active_sources(cfg, args.only):
        gap, last = src.get("min_interval_minutes"), to_dt(state["last_fetch"].get(src["name"]))
        if gap and last and now - last < timedelta(minutes=gap):
            log.info("skip %-28s (polled %d min ago, interval %d)", src["name"], (now - last).seconds // 60, gap)
            continue
        due.append(src)

    collected: list[Job] = []
    with ThreadPoolExecutor(max_workers=cfg.get("workers", 6)) as ex:
        futs = {ex.submit(fetch_source, src): src for src in due}
        for f in as_completed(futs):
            src = futs[f]
            try:
                jobs = f.result()
                state["last_fetch"][src["name"]] = now.isoformat(timespec="seconds")
                collected += jobs
                log.info("ok   %-28s %4d items", src["name"], len(jobs))
            except Exception as e:  # one broken source must not kill the run
                log.warning("FAIL %-28s %s: %s", src["name"], type(e).__name__, e)

    seen, batch_keys, fresh = state["seen"], set(), []
    for job in collected:
        if not job.link or not evaluate(job, search, cfg.get("max_age_days", 14), now):
            continue
        ks = job_keys(job)
        if any(k in seen or k in batch_keys for k in ks):
            continue
        batch_keys.update(ks)
        fresh.append(job)

    if args.dry_run:
        print(render_section(fresh, now) if fresh else "No new matches.")
        return len(fresh)

    if fresh:
        write_md(out_path, fresh, now)
        for k in batch_keys:
            seen[k] = now.isoformat(timespec="seconds")
        notify(cfg, fresh)
    save_state(state_path, state, now)
    log.info("%d new match(es)%s", len(fresh), f" -> {out_path}" if fresh else "")
    return len(fresh)


def check(cfg: dict, args) -> None:
    """Fetch each source and print raw results; use this to tune selectors and URL patterns."""
    for src in active_sources(cfg, args.only):
        try:
            jobs = fetch_source(src)
            print(f"[OK]   {src['name']}: {len(jobs)} items")
            for j in jobs[:3]:
                print(f"         {j.title[:70]!r} -> {j.link}")
            if not jobs:
                print("         (0 items - check the URL / link_pattern / selectors)")
        except Exception as e:
            print(f"[FAIL] {src['name']}: {type(e).__name__}: {e}")


def main() -> None:
    ap = argparse.ArgumentParser(description="Watch job boards and log new matches to Markdown.")
    ap.add_argument("-c", "--config", default="config.yaml")
    ap.add_argument("--watch", type=int, metavar="MIN", help="loop forever, one pass every MIN minutes")
    ap.add_argument("--check", action="store_true", help="test sources, write nothing")
    ap.add_argument("--dry-run", action="store_true", help="print new matches, write nothing")
    ap.add_argument("--only", nargs="+", metavar="NAME", help="only these source names")
    ap.add_argument("-v", "--verbose", action="store_true")
    args = ap.parse_args()
    logging.basicConfig(level=logging.DEBUG if args.verbose else logging.INFO,
                        format="%(asctime)s %(levelname)-7s %(message)s", datefmt="%H:%M:%S")

    cfg_path = Path(args.config).resolve()
    cfg = load_config(cfg_path)
    base = cfg_path.parent

    if args.check:
        return check(cfg, args)
    if not args.watch:
        run_once(cfg, base, args)
        return
    try:
        while True:
            run_once(cfg, base, args)
            time.sleep(args.watch * 60)
            cfg = load_config(cfg_path)  # pick up config edits without restarting
    except KeyboardInterrupt:
        print("\nstopped")


if __name__ == "__main__":
    main()
